#!/usr/bin/env node
// Builds the scripting reference pages from two inputs:
//
//   src/data/cli-structure.json  WHAT exists: command names, aliases, switch and option
//                                names, read from linscp-cli. Refresh with --refresh.
//   src/data/cli.yaml            HOW we describe it: every summary, syntax, explanation
//                                and example, written for this site.
//
// No text from the program's own help output is published; only names are taken from it.
// The run fails when the program has a command, switch or option that cli.yaml does not
// describe, or when cli.yaml describes one the program no longer has.
//
//   node scripts/gen-cli-reference.mjs                         generate pages
//   node scripts/gen-cli-reference.mjs --check                 only validate
//   LINSCP_CLI=/path/linscp-cli node scripts/gen-cli-reference.mjs --refresh

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const STRUCT = join(root, 'src/data/cli-structure.json');
const TEXTS = join(root, 'src/data/cli.yaml');
const OUT = join(root, 'src/content/docs/manual/reference/commands');
const SWITCHES_PAGE = join(root, 'src/content/docs/manual/reference/linscp-cli-switches.md');

const args = new Set(process.argv.slice(2));

// ---------- 1. structure from the binary ----------
function run(bin, argv, input) {
	return execFileSync(bin, argv, { input, encoding: 'utf8', timeout: 20000, stdio: ['pipe', 'pipe', 'pipe'] });
}

function refresh() {
	const bin = process.env.LINSCP_CLI;
	if (!bin) throw new Error('set LINSCP_CLI to the linscp-cli binary');
	const version = (run(bin, ['/help']).match(/Version\s+([\w.]+)/) ?? [])[1] ?? 'unknown';

	const usage = run(bin, ['/help']);
	const switches = [...usage.matchAll(/^ {2}(\/[a-z]+)=?\s/gm)].map((m) => m[1]);

	const list = run(bin, [], 'help\nexit\n');
	const names = [...list.replace(/^linscp> .*$/gm, '').matchAll(/^([a-z]+)[ \t]+\S/gm)].map((m) => m[1]);
	const commands = {};
	for (const name of [...new Set(names)]) {
		const out = run(bin, [], `help ${name}\nexit\n`);
		const section = (label) => {
			const m = out.match(new RegExp(`^${label}:\\n((?:  .*\\n?)+)`, 'm'));
			return m ? m[1] : '';
		};
		commands[name] = {
			aliases: section('alias').trim().split(/,\s*/).filter(Boolean),
			switches: [...section('switches').matchAll(/^ {2}(-[a-z]+)/gm)].map((m) => m[1]),
			options: (section('effective options') || section('effective option')).trim().split(/,\s*/).filter(Boolean),
		};
		if (name === 'option') {
			commands[name].scriptOptions = [...section('options are').matchAll(/^ {2}([a-z]+)\s/gm)].map((m) => m[1]);
		}
	}
	const data = { source: 'linscp-cli', version, switches, commands };
	writeFileSync(STRUCT, JSON.stringify(data, null, '\t') + '\n');
	console.log(`structure: ${Object.keys(commands).length} commands, ${switches.length} switches (linscp-cli ${version})`);
}

// ---------- 2. validate ----------
function diff(kind, have, want) {
	const problems = [];
	for (const x of have) if (!(x in want)) problems.push(`missing description for ${kind} ${x}`);
	for (const x of Object.keys(want)) if (!have.includes(x)) problems.push(`${kind} ${x} is described but linscp-cli has no such thing`);
	return problems;
}

function validate(s, t) {
	const p = [];
	p.push(...diff('command', Object.keys(s.commands), t.commands ?? {}));
	p.push(...diff('program switch', s.switches, t.switches ?? {}));
	for (const [name, c] of Object.entries(s.commands)) {
		const d = t.commands?.[name];
		if (!d) continue;
		for (const f of ['summary', 'syntax', 'body']) if (!d[f]) p.push(`command ${name}: no ${f}`);
		p.push(...diff(`switch of ${name}:`, c.switches, d.switches ?? {}));
		if (c.scriptOptions) p.push(...diff('script option', c.scriptOptions, t.options ?? {}));
	}
	return p;
}

// ---------- 3. render ----------
const yamlStr = (s) => JSON.stringify(String(s));
const header = (fm) =>
	'---\n' +
	'editUrl: false\n' +
	Object.entries(fm)
		.map(([k, v]) => (typeof v === 'object' ? `${k}:\n${Object.entries(v).map(([a, b]) => `  ${a}: ${b}`).join('\n')}` : `${k}: ${v}`))
		.join('\n') +
	'\n---\n\n<!-- Generated by scripts/gen-cli-reference.mjs from src/data/cli.yaml. Do not edit. -->\n\n';

function commandPage(name, c, d, order) {
	let md = header({ title: yamlStr(name), description: yamlStr(d.summary), generated: true, sidebar: { order } });
	md += '## Syntax\n\n```text\n' + d.syntax.trim() + '\n```\n\n';
	md += d.body.trim() + '\n\n';
	if (c.aliases.length) md += `**Also available as** ${c.aliases.map((a) => `\`${a}\``).join(', ')}.\n\n`;
	if (c.switches.length) {
		md += '## Switches\n\n| Switch | What it does |\n|---|---|\n';
		for (const sw of c.switches) md += `| \`${d.switchSyntax?.[sw] ?? sw}\` | ${d.switches[sw]} |\n`;
		md += '\n';
	}
	if (c.options.length) {
		md += '## Affected by\n\n' + c.options.map((o) => `[\`${o}\`](../option/#${o})`).join(', ') + ' (see `option`).\n\n';
	}
	if (name === 'option') {
		md += '## Script options\n\n';
		for (const o of c.scriptOptions) {
			const od = optionsText[o];
			md += `### ${o}\n\n\`${od.values}\`\n\n${od.text.trim()}\n\n`;
		}
	}
	if (d.examples?.length) {
		md += '## Examples\n\n';
		for (const e of d.examples) md += (e.note ? `${e.note}\n\n` : '') + '```sh\n' + e.code.trim() + '\n```\n\n';
	}
	return md;
}

function indexPage(s, t) {
	let md = header({
		title: '"Script commands"',
		description: yamlStr('Every command you can use in a linscp-cli script or session, with links to the details.'),
		generated: true,
		sidebar: { order: 0, label: 'All commands' },
	});
	md += (t.intro ?? '').trim() + '\n\n| Command | Purpose |\n|---|---|\n';
	for (const name of Object.keys(s.commands).sort()) md += `| [\`${name}\`](${name}/) | ${t.commands[name].summary} |\n`;
	return md;
}

function switchesPage(s, t) {
	let md = header({
		title: '"linscp-cli command-line switches"',
		description: yamlStr('Options you can pass to linscp-cli when you start it.'),
		generated: true,
		sidebar: { order: 1 },
	});
	md += (t.switchesIntro ?? '').trim() + '\n\n| Switch | What it does |\n|---|---|\n';
	for (const sw of s.switches) md += `| \`${t.switchSyntax?.[sw] ?? sw}\` | ${t.switches[sw]} |\n`;
	return md;
}

let optionsText = {};

// ---------- main ----------
if (args.has('--refresh')) refresh();
const s = JSON.parse(readFileSync(STRUCT, 'utf8'));
const t = YAML.parse(readFileSync(TEXTS, 'utf8')) ?? {};
optionsText = t.options ?? {};
const problems = validate(s, t);
if (problems.length) {
	console.error(`cli.yaml does not match linscp-cli ${s.version}:\n  ` + problems.join('\n  '));
	process.exit(1);
}
if (args.has('--check')) {
	console.log('cli.yaml covers every command, switch and option.');
	process.exit(0);
}
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'index.md'), indexPage(s, t));
Object.keys(s.commands)
	.sort()
	.forEach((name, i) => writeFileSync(join(OUT, `${name}.md`), commandPage(name, s.commands[name], t.commands[name], i + 1)));
writeFileSync(SWITCHES_PAGE, switchesPage(s, t));
console.log(`wrote ${Object.keys(s.commands).length + 2} pages`);
